<script>
    let bleachedChart = null;

    function initBleachedChart(labels, dataValues, bgColors, maxScale) {
        const ctx = document.getElementById('bleachedOilTankChart').getContext('2d');
        
        if (bleachedChart) { bleachedChart.destroy(); }

        bleachedChart = new Chart(ctx, {
            type: 'bar',
            data: {
                labels: labels,
                datasets: [{
                    label: 'Current Volume',
                    data: dataValues,
                    backgroundColor: bgColors,
                    borderRadius: 4,
                    borderSkipped: false,
                    barPercentage: 0.7,
                }]
            },
            options: {
                responsive: true,
                maintainAspectRatio: false,
                plugins: {
                    legend: { display: false },
                    tooltip: {
                        backgroundColor: 'rgba(255, 255, 255, 0.9)',
                        titleColor: '#881337', // Rose-900
                        bodyColor: '#475569',
                        borderColor: '#fb7185', // Rose-400
                        borderWidth: 1,
                        padding: 10,
                        callbacks: {
                            label: function(context) {
                                return ` Stok: ${new Intl.NumberFormat('id-ID').format(context.raw)} Kg`;
                            }
                        }
                    }
                },
                scales: {
                    y: {
                        beginAtZero: true,
                        max: maxScale, // Dinamis tergantung group
                        grid: { borderDash: [2, 4] },
                        title: { display: true, text: 'Volume (Kg)' }
                    },
                    x: {
                        grid: { display: false },
                        ticks: { autoSkip: false, maxRotation: 90, minRotation: 0, font: { size: 10 } }
                    }
                }
            }
        });
    }

    function updateBleachedChart() {
        const group = document.getElementById('tankGroupSelector').value;

        // Data Dummy (Simulasi)
        // 6T1-6T7 (11k), 6T8-9 (Empty), 6T10-12 (12k), 6T13-14 (13.5k), 6T15 (80k)
        
        let allLabels = ['6T1', '6T2', '6T3', '6T4', '6T5', '6T6', '6T7', '6T8', '6T9', '6T10', '6T11', '6T12', '6T13', '6T14', '6T15'];
        // Isi data acak sesuai kapasitas
        let allData = [10500, 10800, 9500, 10200, 5000, 10900, 8000, 0, 0, 11500, 11000, 4500, 13000, 12500, 75000];
        
        let labels = [];
        let data = [];
        let colors = [];
        let maxY = 15000; // Default max scale for small tanks

        allLabels.forEach((lbl, index) => {
            let val = allData[index];
            let shouldAdd = false;

            if (group === 'ALL') shouldAdd = true;
            else if (group === 'SMALL' && lbl !== '6T15') shouldAdd = true;
            else if (group === 'LARGE' && lbl === '6T15') shouldAdd = true;
            else if (group === 'AVAILABLE' && val === 0) shouldAdd = true;

            if (shouldAdd) {
                labels.push(lbl);
                data.push(val);
                
                // Color logic
                if (val === 0) colors.push('rgba(203, 213, 225, 0.5)'); // Gray for empty
                else if (lbl === '6T15') colors.push('rgba(79, 70, 229, 0.7)'); // Indigo for Large
                else colors.push('rgba(225, 29, 72, 0.7)'); // Rose for standard
            }
        });

        // Adjust scale if showing large tank
        if (group === 'ALL' || group === 'LARGE') {
            maxY = 85000;
        }

        initBleachedChart(labels, data, colors, maxY);
    }

    // Init
    document.addEventListener('DOMContentLoaded', updateBleachedChart);
</script>